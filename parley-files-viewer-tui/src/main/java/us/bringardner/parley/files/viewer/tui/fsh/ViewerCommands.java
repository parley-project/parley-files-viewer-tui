package us.bringardner.parley.files.viewer.tui.fsh;

import java.util.List;

import us.bringardner.fsh.ShellCommand;
import us.bringardner.fsh.spi.CommandProvider;

/** The commands this plugin adds to fsh: view, edit and search. */
public class ViewerCommands implements CommandProvider {

	@Override
	public List<ShellCommand> commands() {
		return List.of(new View(), new Edit(), new Search());
	}
}
